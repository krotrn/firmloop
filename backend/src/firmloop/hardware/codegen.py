"""Generate ``channels.generated.cpp`` / ``drivers.generated.cpp`` (ARCHITECTURE section 4.5)."""

from firmloop.hardware.manifest import Channel, ChannelType, Kind
from firmloop.hardware.registry import Registry

HEADER = '// Generated by firmloop codegen. Do not edit.\n#include "FirmLoopInternal.h"\n'

_TYPES: dict[ChannelType, str] = {
    "float": "Type::Float",
    "int": "Type::Int",
    "bool": "Type::Bool",
    "text": "Type::Text",
}
_KINDS: dict[Kind, str] = {
    "sensor": "Kind::Sensor",
    "actuator": "Kind::Actuator",
    "display": "Kind::Display",
}


def c_string(value: str) -> str:
    """Quote ``value`` as a C string literal (non-printable / non-ASCII bytes as octal)."""
    out: list[str] = []
    for byte in value.encode("utf-8"):
        ch = chr(byte)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif 0x20 <= byte < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\{byte:03o}")
    return '"' + "".join(out) + '"'


def _neutral(channel: Channel) -> str:
    value = channel.neutral
    if isinstance(value, str) or value is None:
        number = 0.0
    else:
        number = float(value)
    return f"{number!r}f"


def generate_channels_cpp(registry: Registry, fw_id: str) -> str:
    """Render ``channels.generated.cpp``: the sorted channel table and ``FW_ID``.

    The definitions have external linkage only because ``FirmLoopInternal.h`` declares
    them ``extern`` first; ``const`` alone would give internal linkage.
    """
    rows = [
        f"    {{{c_string(c.id)}, {_TYPES[c.type]}, {_KINDS[c.kind]}, {_neutral(c)}}},"
        for c in sorted(registry.channels.values(), key=lambda c: c.id)
    ]
    body = "\n".join(rows)
    return (
        f"{HEADER}\nnamespace fl {{\n\n"
        f"const ChannelDef CHANNELS[] = {{\n{body}\n}};\n"
        f"const uint8_t CHANNEL_COUNT = {len(rows)};\n"
        f"const char* const FW_ID = {c_string(fw_id)};\n\n"
        "}  // namespace fl\n"
    )


def generate_drivers_cpp(registry: Registry) -> str:
    """Render ``drivers.generated.cpp``: driver objects plus the ``DRIVERS`` table.

    Pins are passed to the driver constructor as ``uint8_t`` args in manifest order.
    ``DRIVERS``/``DRIVER_COUNT`` get external linkage only because ``FirmLoopInternal.h``
    declares them ``extern`` first.
    """
    comps = [registry.components[cid] for cid in sorted(registry.components)]
    includes = "".join(f'#include "src/{m.id}/driver.h"\n' for m in comps)
    # Constructor args are the pins in manifest (YAML key) order; no sorting.
    decls = "".join(
        f"static {m.driver.class_} driver_{m.id}({', '.join(str(p) for p in m.pins.values())});\n"
        for m in comps
    )
    ptrs = "".join(f"    &driver_{m.id},\n" for m in comps)
    return (
        f"{HEADER}{includes}\n{decls}\nnamespace fl {{\n\n"
        f"Driver* const DRIVERS[] = {{\n{ptrs}}};\n"
        f"const uint8_t DRIVER_COUNT = {len(comps)};\n\n"
        "}  // namespace fl\n"
    )
