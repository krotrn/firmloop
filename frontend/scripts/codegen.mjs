// Generates src/types/generated/{api,spec,events,events-schema}.ts from the backend JSON schemas.
//   node scripts/codegen.mjs [--schemas <dir>] [--out <dir>] [--check]
// With --check, nothing is written to --out: the output is generated in memory and
// compared with the files already there; the exit code is non-zero when any differ, is
// missing, or when the folder holds a file the codegen does not write.
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { parseArgs } from "node:util";

import { compile } from "json-schema-to-typescript";
import openapiTS, { astToString } from "openapi-typescript";

const HEADER = [
  "/**",
  " * This file is generated by `make schemas`. Do not edit it by hand;",
  " * change the backend models and run `make schemas` instead.",
  " */",
  "",
  "",
].join("\n");

const { values } = parseArgs({
  options: {
    schemas: { type: "string", default: "../shared/schemas" },
    out: { type: "string", default: "src/types/generated" },
    check: { type: "boolean", default: false },
  },
});

async function readJson(name) {
  const file = path.join(values.schemas, name);
  let text;
  try {
    text = await readFile(file, "utf8");
  } catch {
    console.error(
      `Cannot read ${file}. Pass --schemas <dir> pointing at shared/schemas, or run \`make schemas\`.`
    );
    process.exit(1);
  }
  return JSON.parse(text);
}

function finish(body) {
  return HEADER + body.trimEnd() + "\n";
}

async function jsonSchemaToTs(file, name) {
  const schema = await readJson(file);
  const body = await compile(schema, name, {
    bannerComment: "",
    format: false,
    additionalProperties: false,
    declareExternallyReferenced: true,
  });
  return finish(body);
}

async function eventsSchemaModule() {
  const schema = await readJson("events.schema.json");
  return finish(
    "export const eventsSchema = " +
      JSON.stringify(schema, null, 2) +
      " as const;"
  );
}

async function generate() {
  const openapi = await readJson("openapi.json");
  const ast = await openapiTS(openapi, { enumValues: true, alphabetize: true });
  return {
    "api.ts": finish(astToString(ast)),
    "spec.ts": await jsonSchemaToTs("spec.schema.json", "Spec"),
    "events.ts": await jsonSchemaToTs("events.schema.json", "Events"),
    "events-schema.ts": await eventsSchemaModule(),
  };
}

const files = await generate();

if (values.check) {
  const stale = [];
  for (const [name, content] of Object.entries(files)) {
    let current = null;
    try {
      current = await readFile(path.join(values.out, name), "utf8");
    } catch {
      // missing counts as stale
    }
    if (current !== content) stale.push(name);
  }
  let present = [];
  try {
    present = await readdir(values.out);
  } catch {
    // a missing folder already shows up as stale files
  }
  const extra = present.filter((name) => !(name in files));
  if (extra.length > 0) {
    console.error(
      `Unexpected files in src/types/generated: ${extra.join(", ")}. ` +
        "Only the codegen writes there; remove them."
    );
  }
  if (stale.length > 0) {
    console.error(
      `Generated types are stale: ${stale.map((n) => `src/types/generated/${n}`).join(", ")}. ` +
        "Run `make schemas` and commit the result."
    );
  }
  if (stale.length > 0 || extra.length > 0) process.exit(1);
} else {
  await mkdir(values.out, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    await writeFile(path.join(values.out, name), content);
  }
}
